package change

import "testing"

// seedGeneratedGlobs and seedFullSuiteTriggers are the seed section 7 defaults.
var (
	seedGeneratedGlobs = []string{"**/*.pb.go", "**/generated.py", "**/*_gen.go"}
	seedTriggers       = []string{
		"go.mod", "go.sum", "pyproject.toml", "uv.lock", "Dockerfile*",
		".gitlab-ci.yml", ".github/workflows/**", "Makefile", "**/conftest.py", "**/testdata/**",
	}
)

func TestFileKindString(t *testing.T) {
	want := map[FileKind]string{
		KindSource: "source", KindTest: "test", KindConfig: "config", KindFixture: "fixture",
		KindGenerated: "generated", KindDocs: "docs", KindLock: "lock", KindBuild: "build",
	}
	for kind, name := range want {
		if got := kind.String(); got != name {
			t.Errorf("FileKind(%d).String() = %q, want %q", int(kind), got, name)
		}
	}
	if got := FileKind(99).String(); got != "unknown" {
		t.Errorf("FileKind(99).String() = %q, want %q", got, "unknown")
	}
}

func TestClassify(t *testing.T) {
	goHeader := []byte("// Code generated by x. DO NOT EDIT.\n\npackage foo\n")
	tests := []struct {
		name string
		path string
		head []byte
		want FileKind
	}{
		// Source.
		{"go source", "main.go", nil, KindSource},
		{"nested go source", "internal/thing/thing.go", []byte("package thing\n"), KindSource},
		{"python source", "app/main.py", nil, KindSource},
		{"other language", "src/lib.rs", nil, KindSource},
		// Test.
		{"go test", "pkg/a_test.go", nil, KindTest},
		{"python test_ prefix", "pkg/test_a.py", nil, KindTest},
		{"python _test suffix", "pkg/a_test.py", nil, KindTest},
		{"file under tests", "tests/helper.go", nil, KindTest},
		{"data under nested tests", "pkg/tests/data.json", nil, KindTest},
		{"testdata go test file", "pkg/testdata/x_test.go", nil, KindTest},
		// Lock.
		{"go.sum", "go.sum", nil, KindLock},
		{"nested go.sum", "sub/go.sum", nil, KindLock},
		{"uv.lock", "uv.lock", nil, KindLock},
		{"any .lock", "deps/yarn.lock", nil, KindLock},
		{"poetry.lock", "poetry.lock", nil, KindLock},
		{"package-lock.json beats config", "web/package-lock.json", nil, KindLock},
		// Build.
		{"go.mod", "go.mod", nil, KindBuild},
		{"nested go.mod", "sub/go.mod", nil, KindBuild},
		{"Makefile", "Makefile", nil, KindBuild},
		{"Dockerfile", "Dockerfile", nil, KindBuild},
		{"Dockerfile variant", "deploy/Dockerfile.dev", nil, KindBuild},
		{"pyproject beats config", "pyproject.toml", nil, KindBuild},
		{"setup.py", "setup.py", nil, KindBuild},
		{"setup.cfg beats config", "setup.cfg", nil, KindBuild},
		{"github workflow beats config", ".github/workflows/ci.yml", nil, KindBuild},
		{"gitlab ci beats config", ".gitlab-ci.yml", nil, KindBuild},
		// Fixture.
		{"testdata file", "pkg/testdata/in.txt", nil, KindFixture},
		{"root testdata beats config", "testdata/x.yaml", nil, KindFixture},
		{"fixtures dir", "fixtures/data.json", nil, KindFixture},
		{"nested fixtures dir", "pkg/fixtures/sample.go", nil, KindFixture},
		{"conftest", "conftest.py", nil, KindFixture},
		{"nested conftest", "pkg/conftest.py", nil, KindFixture},
		{"conftest under tests is a test", "tests/conftest.py", nil, KindTest},
		// Docs.
		{"markdown", "README.md", nil, KindDocs},
		{"nested markdown", "pkg/NOTES.md", nil, KindDocs},
		{"rst", "guide.rst", nil, KindDocs},
		{"txt", "notes.txt", nil, KindDocs},
		{"LICENSE", "LICENSE", nil, KindDocs},
		{"docs dir", "docs/conf.py", nil, KindDocs},
		// Config.
		{"yaml", "a.yaml", nil, KindConfig},
		{"yml", "deploy/b.yml", nil, KindConfig},
		{"json", "c.json", nil, KindConfig},
		{"toml", "d.toml", nil, KindConfig},
		{"ini", "e.ini", nil, KindConfig},
		{"cfg", "f.cfg", nil, KindConfig},
		{"env", "prod.env", nil, KindConfig},
		{"properties", "app.properties", nil, KindConfig},
		// Generated by glob, even for a test-looking name.
		{"pb.go glob", "api/v1/api.pb.go", nil, KindGenerated},
		{"generated.py glob", "src/generated.py", nil, KindGenerated},
		{"_gen.go glob", "a/x_gen.go", nil, KindGenerated},
		{"gen test file is a test", "a/x_gen_test.go", nil, KindTest},
		{"glob beats test", "a/api.pb.go", nil, KindGenerated},
		// Generated by header, without a glob match.
		{"go header", "pkg/foo.go", goHeader, KindGenerated},
		{"go header beats test", "pkg/foo_test.go", goHeader, KindGenerated},
		{"go header after license and build tag", "pkg/foo.go",
			[]byte("// Copyright x\n\n//go:build linux\n\n/* block\ncomment */\n// Code generated by tool v1.2. DO NOT EDIT.\npackage foo\n"), KindGenerated},
		{"go header with CRLF", "pkg/foo.go", []byte("// Code generated by x. DO NOT EDIT.\r\npackage foo\r\n"), KindGenerated},
		{"go header after BOM", "pkg/foo.go", append([]byte("\xef\xbb\xbf"), goHeader...), KindGenerated},
		{"go header after package clause is ignored", "pkg/foo.go",
			[]byte("package foo\n\n// Code generated by x. DO NOT EDIT.\n"), KindSource},
		{"go header wrong case", "pkg/foo.go", []byte("// Code generated by x. do not edit.\npackage foo\n"), KindSource},
		{"go header missing marker", "pkg/foo.go", []byte("// Code generated by x.\npackage foo\n"), KindSource},
		{"go header indented", "pkg/foo.go", []byte("  // Code generated by x. DO NOT EDIT.\npackage foo\n"), KindSource},
		{"go header on non-go file", "notes.txt", goHeader, KindDocs},
		{"python marker first line", "pkg/proto_pb2.py", []byte("# Generated by the compiler.\nx = 1\n"), KindGenerated},
		{"python marker beats test", "pkg/test_x.py", []byte("# Generated by the compiler.\n"), KindGenerated},
		{"python marker not first line", "pkg/proto_pb2.py", []byte("x = 1\n# Generated by the compiler.\n"), KindSource},
		{"python marker on markdown", "docs/generated.md", []byte("# Generated reports\n"), KindDocs},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := Classify(tc.path, tc.head, seedGeneratedGlobs); got != tc.want {
				t.Errorf("Classify(%q) = %v, want %v", tc.path, got, tc.want)
			}
		})
	}
}

func TestClassifyGeneratedGlobsAreCallerSupplied(t *testing.T) {
	if got := Classify("gen/out.go", nil, nil); got != KindSource {
		t.Errorf("without globs Classify = %v, want source", got)
	}
	if got := Classify("gen/out.go", nil, []string{"gen/**"}); got != KindGenerated {
		t.Errorf("with gen/** Classify = %v, want generated", got)
	}
}
