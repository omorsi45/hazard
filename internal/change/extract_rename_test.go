// uniqueGo returns a Go file whose contents share nothing with the file of any
// other tag, so git pairs a rename of it with the right counterpart only.
func uniqueGo(tag string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "package %s\n\n", tag)
	for i := 1; i <= 12; i++ {
		fmt.Fprintf(&b, "// %s%d reports %s-%d.\nfunc %s%d() string { return \"%s-%d\" }\n\n", tag, i, tag, i, tag, i, tag, i)
	}
	return b.String()
}

const (
	generatedLine = "// Code generated by x. DO NOT EDIT.\n\n"
	conftestText  = "import pytest\n\n\n@pytest.fixture\ndef shared():\n    return 1\n\n\ndef other():\n    return 2\n"
)

// ---- world C: renames whose old and new paths classify differently ----

var worldC shared

func buildWorldC() (*history, string) {
	h := &history{}
	m1 := h.commit(heads("main"), 0, "base",
		put("x.pb.go", uniqueGo("xpb")),
		put("foo_test.go", uniqueGo("footest")),
		put("testdata/in.go", uniqueGo("indata")),
		put("conftest.py", conftestText),
		put("gen_old.go", generatedLine+uniqueGo("genold")),
		put("y.go", uniqueGo("yplain")),
		put("hdr_old.go", uniqueGo("hdrold")),
		put("a_test.go", uniqueGo("atest")),
		put("same_old.go", uniqueGo("same")),
	)
	h.commit(heads("main"), m1, "renames",
		rename("x.pb.go", "x.go"),
		rename("foo_test.go", "foo.go"),
		rename("testdata/in.go", "in.go"),
		rename("conftest.py", "helpers.py"),
		// The header is removed on the way: only the base contents say generated.
		rename("gen_old.go", "plain.go"),
		put("plain.go", uniqueGo("genold")),
		rename("y.go", "y.pb.go"),
		// The header is added on the way: only the head contents say generated.
		rename("hdr_old.go", "hdr_new.go"),
		put("hdr_new.go", generatedLine+uniqueGo("hdrold")),
		rename("a_test.go", "b_test.go"),
		rename("same_old.go", "sub/same_new.go"),
	)
	return h, "main"
}

func TestExtractRenameKinds(t *testing.T) {
	t.Parallel()
	r := worldC.get(t, "worldC", buildWorldC)
	opts := testOptions()
	opts.Base, opts.Head = r.sha(1), r.sha(2)
	cs := mustExtract(t, r.dir, opts)

	for _, tc := range []struct {
		name, path, oldPath string
		kind, oldKind       FileKind
	}{
		{"generated by glob on the old path only", "x.go", "x.pb.go", KindSource, KindGenerated},
		{"test on the old path only", "foo.go", "foo_test.go", KindSource, KindTest},
		{"fixture directory on the old path only", "in.go", "testdata/in.go", KindSource, KindFixture},
		{"conftest on the old path only", "helpers.py", "conftest.py", KindSource, KindFixture},
		{"generated header on the old contents only", "plain.go", "gen_old.go", KindSource, KindGenerated},
		{"generated by glob on the new path only", "y.pb.go", "y.go", KindGenerated, KindSource},
		{"generated header on the new contents only", "hdr_new.go", "hdr_old.go", KindGenerated, KindSource},
		{"test to test", "b_test.go", "a_test.go", KindTest, KindTest},
		{"source to source", "sub/same_new.go", "same_old.go", KindSource, KindSource},
	} {
		t.Run(tc.name, func(t *testing.T) {
			f := fileOf(t, cs, tc.path)
			if f.Status != "R" || f.OldPath != tc.oldPath {
				t.Fatalf("%s = %+v, want a rename from %s", tc.path, f, tc.oldPath)
			}
			if f.Kind != tc.kind || f.OldKind != tc.oldKind {
				t.Errorf("%s from %s: Kind %v OldKind %v, want Kind %v OldKind %v", tc.path, tc.oldPath, f.Kind, f.OldKind, tc.kind, tc.oldKind)
			}
		})
	}
}

// TestExtractOldKindEqualsKindExceptForRenames checks that OldKind equals Kind
// for every status other than a rename, including a deleted file (classified
// from its base contents).
func TestExtractOldKindEqualsKindExceptForRenames(t *testing.T) {
	t.Parallel()
	r := worldA.get(t, "worldA", buildWorldA)
	opts := testOptions()
	opts.Base, opts.Head = r.sha(1), r.sha(2)
	cs := mustExtract(t, r.dir, opts)

	kinds := map[FileKind]bool{}
	for _, f := range cs.Files {
		kinds[f.Kind] = true
		if f.OldKind != f.Kind {
			t.Errorf("%s (status %s): OldKind %v, want %v (the same as Kind)", f.Path, f.Status, f.OldKind, f.Kind)
		}
	}
	// The check above is only meaningful if the fixture mixes kinds.
	if len(kinds) < 6 {
		t.Errorf("fixture covers %d kinds, want at least 6", len(kinds))
	}
	if f := fileOf(t, cs, "kinds/gone_header.go"); f.Status != "D" || f.Kind != KindGenerated {
		t.Errorf("kinds/gone_header.go = %+v, want a deleted generated file", f)
	}
}

// ---- repository configuration must not change what Extract reports ----

func TestExtractRenameDetectionIgnoresRepoConfig(t *testing.T) {
	t.Parallel()
	body := "one\ntwo\nthree\nfour\nfive\nsix\nseven\neight\n"
	h := &history{}
	m1 := h.commit(heads("main"), 0, "base", put("old/name.txt", body))
	m2 := h.commit(heads("main"), m1, "rename", rename("old/name.txt", "new/name.txt"))
	r := newRepo(t, h, "main", false)
	r.git(t, "config", "diff.renames", "false")

	// Premise: with this configuration a plain git diff sees a delete and an add.
	plain := r.git(t, "diff", "--name-status", r.sha(m1), r.sha(m2))
	if strings.Contains(plain, "R") || !strings.Contains(plain, "D\told/name.txt") || !strings.Contains(plain, "A\tnew/name.txt") {
		t.Fatalf("premise: git diff --name-status with diff.renames=false = %q, want a delete and an add", plain)
	}

	opts := testOptions()
	opts.Base, opts.Head = r.sha(m1), r.sha(m2)
	cs := mustExtract(t, r.dir, opts)
	wantPaths(t, cs, "new/name.txt")
	if f := fileOf(t, cs, "new/name.txt"); f.Status != "R" || f.OldPath != "old/name.txt" || len(f.Hunks) != 0 {
		t.Errorf("new/name.txt = %+v, want a pure rename from old/name.txt", f)
	}
}

func TestExtractNonASCIIPathsWithQuotePathEnabled(t *testing.T) {
	t.Parallel()
	const (
		modified = "ünï cödé/ß.go"
		oldName  = "dossier é/ancien.go"
		newName  = "dossier é/nouveau ñ.go"
		fresh    = "ünï cödé/néw.go"
	)
	h := &history{}
	m1 := h.commit(heads("main"), 0, "base",
		put(modified, goBase), put(oldName, uniqueGo("ancien")))
	m2 := h.commit(heads("main"), m1, "change",
		put(modified, replaceLine(goBase, 7, alphaEdited)), rename(oldName, newName))
	r := newRepo(t, h, "main", true)
	r.git(t, "config", "core.quotePath", "true")

	// Premise: this configuration makes plain git print the path quoted and escaped.
	if listed := r.git(t, "ls-files"); !strings.Contains(listed, `"\303\274n\303\257 c\303\266d\303\251/`) {
		t.Fatalf("premise: git ls-files with core.quotePath=true = %q, want quoted octal escapes", listed)
	}

	t.Run("committed range", func(t *testing.T) {
		opts := testOptions()
		opts.Base, opts.Head = r.sha(m1), r.sha(m2)
		cs := mustExtract(t, r.dir, opts)
		wantPaths(t, cs, newName, modified)
		wantHunks(t, fileOf(t, cs, modified), hunk(7, 1, 7, 1, "Alpha"))
		if f := fileOf(t, cs, newName); f.Status != "R" || f.OldPath != oldName {
			t.Errorf("%s = %+v, want a rename from %s", newName, f, oldName)
		}
	})
	t.Run("working tree", func(t *testing.T) {
		r.write(t, fresh, "package fresh\n")
		opts := testOptions()
		opts.Base = r.sha(m1)
		cs := mustExtract(t, r.dir, opts)
		if f := fileOf(t, cs, fresh); f.Status != "A" {
			t.Errorf("%s = %+v, want an untracked addition", fresh, f)
		}
		fileOf(t, cs, modified)
		fileOf(t, cs, newName)
	})
}

// TestRunGitIgnoresQuotePathConfig checks that runGit, through which every git
// call goes, prints paths unquoted whatever the user's core.quotePath says.
func TestRunGitIgnoresQuotePathConfig(t *testing.T) {
	t.Parallel()
	const name = "ünï cödé/ß.go"
	h := &history{}
	h.commit(heads("main"), 0, "base", put(name, goBase))
	r := newRepo(t, h, "main", false)
	r.git(t, "config", "core.quotePath", "true")

	if plain := r.git(t, "ls-tree", "-r", "--name-only", "HEAD"); !strings.HasPrefix(plain, `"`) {
		t.Fatalf("premise: git ls-tree with core.quotePath=true = %q, want a quoted path", plain)
	}
	out, err := runGit(context.Background(), r.dir, nil, "ls-tree", "-r", "--name-only", "HEAD")
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.TrimSpace(string(out)); got != name {
		t.Errorf("runGit ls-tree = %q, want the unquoted path %q", got, name)
	}
}
