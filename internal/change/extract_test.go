func TestExtractCommittedRange(t *testing.T) {
	t.Parallel()
	r := worldA.get(t, "worldA", buildWorldA)
	opts := testOptions()
	opts.Base, opts.Head = r.sha(1), r.sha(2)
	cs := mustExtract(t, r.dir, opts)

	if cs.BaseSHA != r.sha(1) || cs.HeadSHA != r.sha(2) || cs.Dirty {
		t.Errorf("BaseSHA %s HeadSHA %s Dirty %v; want %s %s false", cs.BaseSHA, cs.HeadSHA, cs.Dirty, r.sha(1), r.sha(2))
	}
	wantPaths(t, cs,
		"--output=x.go", "-rf.go", "bin/logo.bin", "dir with space/héllo wörld.go",
		"docs/README.md", "docs/guide.md",
		"go/added.go", "go/after_broken.go", "go/broken_base.go", "go/broken_base_insert.go", "go/broken_head.go", "go/deleted_func.go",
		"go/ins_blank.go", "go/ins_body.go", "go/ins_boundary.go", "go/ins_import.go", "go/ins_top.go",
		"go/modified.go", "go/pkg/rename_new.go", "go/pure_new.go", "go/removed.go",
		"kinds/a_test.go", "kinds/api.pb.go", "kinds/config.yaml", "kinds/gen_header.go", "kinds/go.sum",
		"kinds/gone_header.go", "kinds/main.go",
		"other/lib.rs", "py/class_edit.py", "py/del_func.py", "py/module_edit.py", "run.sh",
		"testdata/blob.bin", "ünï cödé/ß.go",
	)

	t.Run("modified function", func(t *testing.T) {
		f := fileOf(t, cs, "go/modified.go")
		if f.Status != "M" || f.Language != "go" || f.Kind != KindSource || f.OldPath != "" || f.Binary || f.Package != "" {
			t.Errorf("file = %+v", f)
		}
		wantHunks(t, f, hunk(7, 1, 7, 1, "Alpha"))
	})
	t.Run("deleted function keeps the old-side symbol", func(t *testing.T) {
		f := fileOf(t, cs, "go/deleted_func.go")
		if len(f.Hunks) != 1 {
			t.Fatalf("hunks = %+v, want one", f.Hunks)
		}
		h := f.Hunks[0]
		// Beta is gone from the head contents: only the base side can name it.
		if h.OldLines != 4 || h.NewLines != 0 || !reflect.DeepEqual(h.Symbols, []string{"Beta"}) {
			t.Errorf("hunk = %+v, want 4 old lines, 0 new lines, symbols [Beta]", h)
		}
	})
	t.Run("insertion hunks", func(t *testing.T) {
		wantHunks(t, fileOf(t, cs, "go/ins_body.go"), hunk(7, 0, 8, 1, "Alpha"))
		// Directly after a declaration both neighbours are affected.
		wantHunks(t, fileOf(t, cs, "go/ins_boundary.go"), hunk(12, 0, 13, 1, "Beta", "Delta"))
		wantHunks(t, fileOf(t, cs, "go/ins_blank.go"), hunk(13, 0, 14, 1, "Z"))
		wantHunks(t, fileOf(t, cs, "go/ins_import.go"), hunk(3, 0, 4, 1, "__file__"))
		wantHunks(t, fileOf(t, cs, "go/ins_top.go"), hunk(0, 0, 1, 1, "__file__"))
	})
	t.Run("added and deleted files", func(t *testing.T) {
		added := fileOf(t, cs, "go/added.go")
		if added.Status != "A" || added.Language != "go" {
			t.Errorf("added = %+v", added)
		}
		wantHunks(t, added, hunk(0, 0, 1, 12, "(*Box).Inc", "Box", "Upper"))
		gone := fileOf(t, cs, "go/removed.go")
		if gone.Status != "D" || gone.Language != "go" {
			t.Errorf("deleted = %+v", gone)
		}
		// A deleted file has no head contents; the old side names every declaration.
		wantHunks(t, gone, hunk(1, 8, 0, 0, "Omega", "Sigma", "Sigma.Total"))
	})
	t.Run("renames", func(t *testing.T) {
		ren := fileOf(t, cs, "go/pkg/rename_new.go")
		if ren.Status != "R" || ren.OldPath != "go/rename_old.go" || ren.Language != "go" {
			t.Errorf("rename = %+v", ren)
		}
		wantHunks(t, ren, hunk(7, 1, 7, 1, "Alpha"))
		pure := fileOf(t, cs, "go/pure_new.go")
		if pure.Status != "R" || pure.OldPath != "go/pure_old.go" || len(pure.Hunks) != 0 {
			t.Errorf("pure rename = %+v", pure)
		}
	})
	t.Run("go parse failure degrades to file level", func(t *testing.T) {
		want := hunk(7, 1, 7, 1, "Alpha", "__file__")
		wantHunks(t, fileOf(t, cs, "go/broken_head.go"), want)
		wantHunks(t, fileOf(t, cs, "go/broken_base.go"), want)
		// A pure insertion consults the base only for the declaration holding the
		// line it follows; an unparsable base must still widen it to the file.
		wantHunks(t, fileOf(t, cs, "go/broken_base_insert.go"), hunk(17, 0, 18, 1, "(*Gamma).Run", "__file__"))
		wantHunks(t, fileOf(t, cs, "go/after_broken.go"), hunk(7, 1, 7, 1, "Alpha"))
	})
	t.Run("python", func(t *testing.T) {
		class := fileOf(t, cs, "py/class_edit.py")
		if class.Language != "python" || class.Kind != KindSource {
			t.Errorf("class_edit = %+v", class)
		}
		wantHunks(t, class, hunk(9, 1, 9, 1, "Box"))
		wantHunks(t, fileOf(t, cs, "py/module_edit.py"), hunk(12, 1, 12, 1, "__file__"))
		deleted := fileOf(t, cs, "py/del_func.py")
		if len(deleted.Hunks) != 1 || deleted.Hunks[0].NewLines != 0 || !reflect.DeepEqual(deleted.Hunks[0].Symbols, []string{"helper"}) {
			t.Errorf("del_func hunks = %+v, want one pure deletion naming helper", deleted.Hunks)
		}
	})
	t.Run("other languages are file level", func(t *testing.T) {
		for _, tc := range []struct {
			path string
			kind FileKind
		}{{"docs/README.md", KindDocs}, {"other/lib.rs", KindSource}} {
			f := fileOf(t, cs, tc.path)
			if f.Language != "" || f.Kind != tc.kind {
				t.Errorf("%s = %+v, want no language and kind %v", tc.path, f, tc.kind)
			}
			if len(f.Hunks) != 1 || !reflect.DeepEqual(f.Hunks[0].Symbols, []string{"__file__"}) {
				t.Errorf("%s hunks = %+v, want one hunk on __file__", tc.path, f.Hunks)
			}
		}
	})
	t.Run("binary files", func(t *testing.T) {
		logo := fileOf(t, cs, "bin/logo.bin")
		if !logo.Binary || logo.Status != "M" || len(logo.Hunks) != 0 || logo.Kind != KindSource {
			t.Errorf("logo = %+v", logo)
		}
		blob := fileOf(t, cs, "testdata/blob.bin")
		if !blob.Binary || blob.Kind != KindFixture || len(blob.Hunks) != 0 {
			t.Errorf("fixture blob = %+v", blob)
		}
		// A binary file is still matched against the full-suite triggers.
		want := []string{"**/testdata/**:testdata/blob.bin", "go.sum:kinds/go.sum"}
		if !reflect.DeepEqual(cs.TriggersFull, want) {
			t.Errorf("TriggersFull = %q, want %q", cs.TriggersFull, want)
		}
	})
	t.Run("mode-only change is not empty", func(t *testing.T) {
		if f := fileOf(t, cs, "run.sh"); f.Status != "M" || len(f.Hunks) != 0 || f.Binary {
			t.Errorf("run.sh = %+v, want Status M and no hunks", f)
		}
	})
	t.Run("kinds", func(t *testing.T) {
		want := map[string]FileKind{
			"kinds/gen_header.go":  KindGenerated, // header only, no glob match
			"kinds/api.pb.go":      KindGenerated, // glob only
			"kinds/gone_header.go": KindGenerated, // deleted: classified from the base contents
			"kinds/a_test.go":      KindTest,
			"docs/guide.md":        KindDocs,
			"kinds/go.sum":         KindLock,
			"kinds/config.yaml":    KindConfig,
			"kinds/main.go":        KindSource,
		}
		for p, kind := range want {
			if got := fileOf(t, cs, p).Kind; got != kind {
				t.Errorf("%s kind = %v, want %v", p, got, kind)
			}
		}
	})
	t.Run("awkward paths", func(t *testing.T) {
		for _, p := range []string{"-rf.go", "dir with space/héllo wörld.go", "ünï cödé/ß.go", "--output=x.go"} {
			f := fileOf(t, cs, p)
			if f.Status != "M" || f.Language != "go" {
				t.Errorf("%q = %+v", p, f)
			}
			wantHunks(t, f, hunk(7, 1, 7, 1, "Alpha"))
		}
	})
	t.Run("files are sorted by path", func(t *testing.T) {
		if got := paths(cs); !sort.StringsAreSorted(got) {
			t.Errorf("paths not sorted: %q", got)
		}
	})
	t.Run("line totals match git numstat over text files", func(t *testing.T) {
		out, err := gitRun(r.dir, "diff", "--numstat", r.sha(1), r.sha(2))
		if err != nil {
			t.Fatal(err)
		}
		var added, removed int
		for _, line := range strings.Split(out, "\n") {
			cols := strings.Split(line, "\t")
			if len(cols) < 3 || cols[0] == "-" { // binary files report "-"
				continue
			}
			a, errA := strconv.Atoi(cols[0])
			d, errD := strconv.Atoi(cols[1])
			if errA != nil || errD != nil {
				t.Fatalf("numstat line %q", line)
			}
			added, removed = added+a, removed+d
		}
		if cs.LinesAdded != added || cs.LinesRemoved != removed || added == 0 {
			t.Errorf("lines +%d -%d, numstat says +%d -%d", cs.LinesAdded, cs.LinesRemoved, added, removed)
		}
	})
}

func TestExtractIgnoresInheritedGitEnvironment(t *testing.T) {
	r := worldA.get(t, "worldA", buildWorldA)
	opts := testOptions()
	opts.Base, opts.Head = r.sha(1), r.sha(2)
	want := paths(mustExtract(t, r.dir, opts))

	// A surrounding git hook exports these; they must not redirect Extract.
	bogus := filepath.Join(t.TempDir(), "elsewhere")
	t.Setenv("GIT_DIR", bogus)
	t.Setenv("GIT_WORK_TREE", bogus)
	t.Setenv("GIT_INDEX_FILE", filepath.Join(bogus, "index"))

	if got := paths(mustExtract(t, r.dir, opts)); !reflect.DeepEqual(got, want) {
		t.Errorf("paths changed under a hostile environment\n got: %q\nwant: %q", got, want)
	}
}

// ---- world B: full-suite triggers ----

var worldB shared

func buildWorldB() (*history, string) {
	h := &history{}
	aText := "module example.com/a\n\ngo 1.26\n\nrequire (\n\tgithub.com/a/b v1.0.0\n\tgithub.com/c/d v2.0.0\n)\n"
	bText := "alpha\nbeta\ngamma\ndelta\nepsilon\nzeta\neta\ntheta\n"
	m1 := h.commit(heads("main"), 0, "base",
		put("go.mod", "module x\n"), put("Makefile", "all:\n"), put("main.go", "package m\n"),
		put("pkg/conftest.py", "a = 1\n"), put("legacy/a.txt", aText), put("other/b.txt", bText))
	m2 := h.commit(heads("main"), m1, "triggers",
		put("go.mod", "module x\n\ngo 1.26\n"), put("pkg/conftest.py", "a = 2\n"),
		put("main.go", "package m\n\nvar X = 1\n"), put("deploy/Dockerfile.dev", "FROM scratch\n"),
		put("sub/testdata/in.txt", "x\n"), put(".github/workflows/ci.yml", "on: push\n"),
		del("Makefile"), rename("legacy/a.txt", "other/a.txt"), rename("other/b.txt", "legacy/b.txt"))
	h.commit(heads("main"), m2, "move go.mod", rename("go.mod", "sub/go.mod"))
	return h, "main"
}

func TestExtractTriggersFull(t *testing.T) {
	t.Parallel()
	r := worldB.get(t, "worldB", buildWorldB)
	extract := func(t *testing.T, from, to int, triggers []string) *ChangeSet {
		t.Helper()
		opts := testOptions()
		opts.FullSuiteTriggers = triggers
		opts.Base, opts.Head = r.sha(from), r.sha(to)
		return mustExtract(t, r.dir, opts)
	}

	t.Run("seed triggers, sorted", func(t *testing.T) {
		got := extract(t, 1, 2, seedTriggers).TriggersFull
		want := []string{
			"**/conftest.py:pkg/conftest.py",
			"**/testdata/**:sub/testdata/in.txt",
			".github/workflows/**:.github/workflows/ci.yml",
			"Dockerfile*:deploy/Dockerfile.dev",
			"Makefile:Makefile", // deleted file
			"go.mod:go.mod",
		}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("TriggersFull\n got: %q\nwant: %q", got, want)
		}
	})
	t.Run("no configured triggers", func(t *testing.T) {
		if got := extract(t, 1, 2, nil).TriggersFull; len(got) != 0 {
			t.Errorf("TriggersFull = %q, want none", got)
		}
	})
	t.Run("overlapping and repeated patterns are deduplicated", func(t *testing.T) {
		got := extract(t, 1, 2, []string{"go.mod", "**/go.mod", "go.mod", "Makefile"}).TriggersFull
		want := []string{"**/go.mod:go.mod", "Makefile:Makefile", "go.mod:go.mod"}
		if !reflect.DeepEqual(got, want) {
			t.Errorf("TriggersFull\n got: %q\nwant: %q", got, want)
		}
	})
	t.Run("rename matches through the old path or the new path", func(t *testing.T) {
		cs := extract(t, 1, 2, []string{"legacy/**"})
		want := []string{"legacy/**:legacy/a.txt", "legacy/**:legacy/b.txt"}
		if !reflect.DeepEqual(cs.TriggersFull, want) {
			t.Errorf("TriggersFull = %q, want %q", cs.TriggersFull, want)
		}
		if f := fileOf(t, cs, "other/a.txt"); f.Status != "R" || f.OldPath != "legacy/a.txt" {
			t.Errorf("other/a.txt = %+v, want a rename from legacy/a.txt", f)
		}
		if f := fileOf(t, cs, "legacy/b.txt"); f.Status != "R" || f.OldPath != "other/b.txt" {
			t.Errorf("legacy/b.txt = %+v, want a rename from other/b.txt", f)
		}
	})
	t.Run("go.mod moved into a subdirectory", func(t *testing.T) {
		cs := extract(t, 2, 3, seedTriggers)
		if f := fileOf(t, cs, "sub/go.mod"); f.Status != "R" || f.OldPath != "go.mod" || f.Kind != KindBuild {
			t.Fatalf("sub/go.mod = %+v, want a build-kind rename from go.mod", f)
		}
		want := []string{"go.mod:go.mod", "go.mod:sub/go.mod"}
		if !reflect.DeepEqual(cs.TriggersFull, want) {
			t.Errorf("TriggersFull = %q, want %q", cs.TriggersFull, want)
		}
	})
}
